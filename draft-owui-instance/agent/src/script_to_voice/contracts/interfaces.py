from typing import Protocol
from .models import (ScriptRevision, IntentProposal, CastingProposal, DirectionProposal,
                     VoicePage, VoiceDesignRequest, VoicePreview, Voice, CompiledChunk, ProviderAudioResult)


class ScriptImporter(Protocol):
    def parse(self, original: bytes, filename: str, *, owner_id: str, project_id: str,
              original_file_id: str) -> ScriptRevision: ...


class IntentPlanner(Protocol):
    async def interpret(self, request: str, revision: ScriptRevision, prior=None) -> IntentProposal: ...


class CastingPlanner(Protocol):
    async def propose(self, request: dict) -> CastingProposal: ...


class DirectionPlanner(Protocol):
    async def annotate(self, request: dict) -> DirectionProposal: ...


class VoiceProvider(Protocol):
    async def list_voices(self, cursor: str | None = None) -> VoicePage: ...
    async def get_voice(self, voice_id: str) -> Voice: ...
    async def design_previews(self, request: VoiceDesignRequest) -> tuple[VoicePreview, ...]: ...
    async def save_preview(self, generated_voice_id: str, name: str, description: str) -> Voice: ...
    async def render(self, chunk: CompiledChunk) -> ProviderAudioResult: ...
